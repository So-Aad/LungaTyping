/**
 * Normalizes text for phrase lookup: lowers case and strips extraneous whitespace.
 */
function normalizePhraseKey(phrase: string): string {
  return phrase.trim().toLowerCase().replace(/\s+/g, ' ')
}

/**
 * Retrieves the Arabic translation of a full phrase.
 */
export function getPhraseTranslation(phrase: string): string | null {
  if (!phrase) return null
  const key = normalizePhraseKey(phrase)

  // Direct lookup
  if (PHRASE_TRANSLATIONS[key]) {
    return PHRASE_TRANSLATIONS[key]
  }

  // Lookup without ending punctuation
  const keyNoPunct = key.replace(/[.!?]+$/, '').trim()
  for (const [k, v] of Object.entries(PHRASE_TRANSLATIONS)) {
    if (k.replace(/[.!?]+$/, '').trim() === keyNoPunct) {
      return v
    }
  }

  return null
}

/**
 * Normalizes a word for dictionary lookup: strips exterior punctuation and lowercases.
 */
export function normalizeWordKey(word: string): string {
  return word.toLowerCase().replace(/^[^\w']+|[^\w']+$/g, '').trim()
}

/**
 * Retrieves the Arabic translation of an individual word with smart morphological fallbacks.
 */
export function getWordTranslation(rawWord: string): string | null {
  const word = normalizeWordKey(rawWord)
  if (!word) return null

  // 1. Direct match
  if (WORD_TRANSLATIONS[word]) {
    return WORD_TRANSLATIONS[word]
  }

  // 2. Contraction or possessive check: "she's" -> "she" + "'s", "father's" -> "father"
  if (word.endsWith("'s")) {
    const base = word.slice(0, -2)
    if (WORD_TRANSLATIONS[base]) {
      return WORD_TRANSLATIONS[base]
    }
  }

  // 3. Plural check: "-s", "-es"
  if (word.endsWith('es') && WORD_TRANSLATIONS[word.slice(0, -2)]) {
    return WORD_TRANSLATIONS[word.slice(0, -2)]
  }
  if (word.endsWith('s') && !word.endsWith('ss') && WORD_TRANSLATIONS[word.slice(0, -1)]) {
    return WORD_TRANSLATIONS[word.slice(0, -1)]
  }

  // 4. Past tense check: "-ed"
  if (word.endsWith('ed')) {
    if (WORD_TRANSLATIONS[word.slice(0, -2)]) return WORD_TRANSLATIONS[word.slice(0, -2)]
    if (WORD_TRANSLATIONS[word.slice(0, -1)]) return WORD_TRANSLATIONS[word.slice(0, -1)]
  }

  // 5. Participle check: "-ing"
  if (word.endsWith('ing')) {
    if (WORD_TRANSLATIONS[word.slice(0, -3)]) return WORD_TRANSLATIONS[word.slice(0, -3)]
    if (WORD_TRANSLATIONS[word.slice(0, -3) + 'e']) return WORD_TRANSLATIONS[word.slice(0, -3) + 'e']
  }

  // 6. Adverb check: "-ly"
  if (word.endsWith('ly') && WORD_TRANSLATIONS[word.slice(0, -2)]) {
    return WORD_TRANSLATIONS[word.slice(0, -2)]
  }

  return null
}
